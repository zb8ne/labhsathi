// Deliberately no `as const` -- that would infer every string as its own
// literal type, and the en/hi objects (same keys, different literal
// values) would then fail to structurally match each other. Widened to
// plain `string` leaves, both translate to the same shape trivially, and
// TranslationShape below still catches a genuinely missing/extra key.
type TranslationShape = {
  [K in keyof (typeof translations)["en"]]: {
    [K2 in keyof (typeof translations)["en"][K]]: string | Record<string, string>;
  };
};
translations satisfies Record<Lang, TranslationShape>;
